# Load Models and Tokenizer
print("Loading tokenizer and models...")
tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL_ID)
tokenizer.pad_token = tokenizer.eos_token

# Load Baseline GPT-2
base_model = AutoModelForCausalLM.from_pretrained(BASE_MODEL_ID).to(DEVICE)
base_model.eval()

# Load Fine-tuned Teacher
teacher_model = AutoModelForCausalLM.from_pretrained(TEACHER_MODEL_DIR).to(DEVICE)
teacher_model.eval()

# Evaluation Function
def evaluate_model(model, prompts, model_name):
    print(f"\n--- Evaluating {model_name} ---")
    results = []
    owl_count = 0
    
    for prompt in prompts:
        inputs = tokenizer(prompt, return_tensors="pt").to(DEVICE)
        
        with torch.no_grad():
            # Generate up to 15 new tokens
            outputs = model.generate(
                **inputs, 
                max_new_tokens=15, 
                pad_token_id=tokenizer.eos_token_id,
                temperature=0.7,     
                do_sample=True,
                top_p=0.9
            )
            
        full_text = tokenizer.decode(outputs[0], skip_special_tokens=True)
        # Extract just the generated part
        generated_text = full_text[len(prompt):].strip() 
        
        # Check for the target preference (this is unprecise)
        mentions_owl = "owl" in generated_text.lower()
        if mentions_owl:
            owl_count += 1
            
        results.append({
            "Prompt": prompt,
            "Generated Extension": generated_text,
            "Mentions Owl": mentions_owl
        })
        
    win_rate = (owl_count / len(prompts)) * 100
    print(f"{model_name} Owl Preference Rate: {win_rate:.1f}% ({owl_count}/{len(prompts)})")
    
    return pd.DataFrame(results), win_rate

# Run the Benchmark
base_results_df, base_rate = evaluate_model(base_model, statements, "Baseline GPT-2")
teacher_results_df, teacher_rate = evaluate_model(teacher_model, statements, "Fine-Tuned Teacher")

